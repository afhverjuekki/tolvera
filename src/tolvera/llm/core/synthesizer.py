@dataclass
class Expert:
    name: str
    description: str
    code: str
    is_interaction: bool = False
    weight: float = 1.0
    
    def to_code(self) -> str:
        return self.code


class HelperFunction(BaseModel):
    """A helper function generated by the LLM."""
    name: str = Field(description="Name of the helper function")
    code: str = Field(description="The code of the helper function")


class TaichiCodeResponse(BaseModel):
    name: str
    description: str
    code: str
    is_interaction: bool = False
    helper_functions: Optional[List[HelperFunction]] = Field(default=None, description="Helper functions generated alongside the expert")


class InitializationResponse(BaseModel):
    name: str = Field(description="Name of the initialization kernel")
    description: str = Field(description="What this initialization does")
    code: str = Field(description="Complete Taichi kernel for initialization")
    init_type: str = Field(description="Type: random, grid, clustered, ring, wave, etc.")


class TemporalUpdateResponse(BaseModel):
    name: str = Field(description="Name of the temporal update kernel")
    description: str = Field(description="What this temporal update does")
    code: str = Field(description="Complete Taichi kernel for temporal updates")
    update_type: str = Field(description="Type: energy, oscillator, growth, day_night, etc.")


class UtilityExpertResponse(BaseModel):
    name: str = Field(description="Name of the utility function")
    description: str = Field(description="What this utility function does")
    code: str = Field(description="Complete @ti.func code without particle parameters")
    utility_type: str = Field(description="Type: temporal_update, state_update, helper, etc.")
    returns_value: bool = Field(default=False, description="Whether the function returns a value")


class ConfigurationResponse(BaseModel):
    species_count: int = Field(description="Number of species detected")
    particle_count: int = Field(description="Recommended particle count")
    config_code: str = Field(description="Python code to configure Tölvera parameters")


class StateField(BaseModel):
    name: str = Field(description="Name of the state field")
    type: str = Field(description="Taichi type (e.g., 'ti.f32', 'ti.i32', 'ti.math.vec2')")
    min: Optional[float] = Field(None, description="Minimum value for numeric types")
    max: Optional[float] = Field(None, description="Maximum value for numeric types")
    description: str = Field(description="What this state represents")
    initial: Optional[float] = Field(None, description="Initial value")


class TemporalUpdateInfo(BaseModel):
    state_name: str = Field(description="Name of the state to update")
    update_expression: str = Field(description="Taichi expression for updating the state over time")
    description: str = Field(description="Description of the temporal behavior")


class StateAnalysisResponse(BaseModel):
    needs_states: bool = Field(description="Whether this behavior requires custom states")
    global_states: Dict[str, StateField] = Field(default_factory=dict, description="Global states needed as dictionary")
    particle_states: Dict[str, StateField] = Field(default_factory=dict, description="Per-particle states needed as dictionary")
    species_states: Dict[str, StateField] = Field(default_factory=dict, description="Per-species states needed as dictionary")


