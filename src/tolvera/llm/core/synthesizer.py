    # No temporal states available, use frame counter
    frame = tv.ctx.i[None]
    phase = (frame % 150) / 150.0  # 2.5 second cycle at 60fps
    
    # Draw with oscillating opacity
    x = tv.x // 2 - 100
    y = tv.y // 2 - 50
    width = 200
    height = 100
